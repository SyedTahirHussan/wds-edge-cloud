"""Aggregate per-seed results into tables and figures, and write the README results block.

Every number in ``summary.md`` and in the README block comes from ``<results>/raw``;
values are mean ± sample standard deviation over seeds. The findings sentences are
assembled from the same tables (which method is lower or higher is computed, not
written by hand).
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from flowmine.config import Config

BEGIN = "<!-- results:begin (generated by `flowmine experiments report`; do not edit) -->"
END = "<!-- results:end -->"
METHOD_NAMES = {
    "rules": "Rule tests only",
    "edge_hw": "Edge, Holt-Winters",
    "edge_mlp": "Edge, neural",
    "central": "Central (spatial + lab)",
    "hybrid": "Hybrid fusion",
}
plt.rcParams.update({"svg.hashsalt": "flowmine", "font.size": 9, "figure.dpi": 110})


def pm(x: pd.Series, digits: int = 3) -> str:
    x = x.dropna()
    if x.empty:
        return "n/a"
    m = float(x.mean())
    if len(x) < 2:
        return f"{m:.{digits}f}"
    return f"{m:.{digits}f} ± {float(x.std(ddof=1)):.{digits}f}"


def table(
    df: pd.DataFrame,
    by: list[str],
    cols: dict[str, str],
    digits: int = 3,
    order: list[str] | None = None,
    rename: Callable[[str], str] | None = None,
) -> str:
    groups = df.groupby(by, sort=False)
    keys = [tuple(row) for row in df[by].drop_duplicates().itertuples(index=False)]
    if order is not None:
        keys = [(k,) for k in order if (k,) in keys]
    head = "| " + " | ".join(by + list(cols.values())) + " |"
    sep = "|" + "---|" * (len(by) + len(cols))
    lines = [head, sep]
    for k in keys:
        g = groups.get_group(k)
        names = [rename(str(v)) if rename else str(v) for v in k]
        lines.append("| " + " | ".join(names + [pm(g[c], digits) for c in cols]) + " |")
    return "\n".join(lines)


def _save(fig: plt.Figure, out: Path, name: str) -> list[str]:
    out.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(out / f"{name}.png", metadata={"Software": None})
    fig.savefig(out / f"{name}.svg", metadata={"Date": None, "Creator": None})
    plt.close(fig)
    return [f"{name}.png", f"{name}.svg"]


def fig_e1(e1: pd.DataFrame, out: Path) -> None:
    types = ["spike", "stuck", "noise_burst", "bias", "drift"]
    fig, ax = plt.subplots(figsize=(7, 3))
    methods = [m for m in METHOD_NAMES if m in set(e1.method)]
    w = 0.8 / len(methods)
    for i, m in enumerate(methods):
        g = e1[(e1.method == m)].groupby("fault_type").recall
        mean, sd = g.mean().reindex(types), g.std().reindex(types).fillna(0)
        ax.bar(np.arange(len(types)) + i * w, mean, w, yerr=sd, label=METHOD_NAMES[m], capsize=2)
    ax.set_xticks(np.arange(len(types)) + 0.4 - w / 2, types)
    ax.set_ylabel("sample recall (test week)")
    ax.set_ylim(0, 1.05)
    ax.legend(fontsize=7, ncol=3, loc="upper left")
    _save(fig, out, "e1_recall_by_fault")


def fig_e2(e2: pd.DataFrame, out: Path) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(9, 3))
    for ax, (kind, unit) in zip(
        axes, (("pressure", "m"), ("flow", "L/s"), ("level", "m")), strict=True
    ):
        sub = e2[e2.kind == kind]
        for m, g in sub.groupby("method"):
            s = g.groupby("gap_min").mae.mean()
            ax.plot(
                s.index, s.values, marker="o", ms=3, label=str(m), lw=2.2 if m == "hybrid" else 1.0
            )
        ax.set_xscale("log")
        ax.set_title(kind)
        ax.set_xlabel("gap length (min)")
        ax.set_ylabel(f"MAE ({unit})")
    axes[0].legend(fontsize=6)
    _save(fig, out, "e2_reconstruction_vs_gap")


def fig_e3(pol: pd.DataFrame, eps: pd.DataFrame, out: Path) -> None:
    fig, (a, b) = plt.subplots(1, 2, figsize=(8, 3))
    g = pol.groupby("policy", sort=False).binary_bytes_per_station_day
    a.bar(list(g.mean().index), g.mean().values, yerr=g.std().fillna(0).values, capsize=3)
    a.set_ylabel("binary bytes / station / day")
    e = eps.groupby("eps_factor")
    b.plot(e.binary_bytes_per_station_day.mean(), e.cloud_error_vs_edge.mean(), marker="o")
    for f, x, y in zip(
        e.groups, e.binary_bytes_per_station_day.mean(), e.cloud_error_vs_edge.mean(), strict=True
    ):
        b.annotate(f"{f:g}×ε", (x, y), fontsize=7)
    b.set_xlabel("binary bytes / station / day (delta policy)")
    b.set_ylabel("cloud error / sensor range")
    _save(fig, out, "e3_uplink")


def fig_e6(e6: pd.DataFrame, out: Path) -> None:
    fig, ax = plt.subplots(figsize=(5, 3))
    order = ["raw", "edge_validated", "hybrid_validated", "clean"]
    g = e6.groupby("input")
    for i, col in enumerate(("rmse_monitored_m", "rmse_unmonitored_m")):
        ax.bar(
            np.arange(4) + i * 0.4,
            g[col].mean().reindex(order),
            0.4,
            yerr=g[col].std().reindex(order).fillna(0),
            capsize=3,
            label=col.replace("rmse_", "").replace("_m", ""),
        )
    ax.set_xticks(np.arange(4) + 0.2, order, fontsize=7)
    ax.set_ylabel("pressure RMSE (m)")
    ax.legend(fontsize=7)
    _save(fig, out, "e6_twin_state_error")


def findings(d: dict[str, pd.DataFrame]) -> list[str]:
    out = []
    e1 = d["e1_detection"]
    ov = e1[e1.fault_type == "overall"].groupby("method").f1.mean()
    best = str(ov.idxmax())
    out.append(
        f"Overall sample F1 (non-gap faults): {METHOD_NAMES[best]} is highest "
        f"({ov[best]:.3f}); the edge-only methods reach "
        f"{ov.get('edge_hw', np.nan):.3f} (Holt-Winters) and {ov.get('edge_mlp', np.nan):.3f} "
        f"(neural), the central methods {ov.get('central', np.nan):.3f}."
    )
    rec = e1.groupby(["method", "fault_type"]).recall.mean()
    for ft in ("bias", "drift", "spike"):
        e, c = rec.get(("edge_hw", ft), np.nan), rec.get(("central", ft), np.nan)
        if max(e, c) < 0.05:
            verdict = "neither detects it"
        elif abs(e - c) < 0.05:
            verdict = "both detect it about equally"
        else:
            verdict = ("the edge" if e > c else "the cloud") + " detects it better"
        out.append(
            f"{ft}: recall {e:.2f} at the edge (Holt-Winters) against {c:.2f} in the cloud; "
            f"{verdict}."
        )
    fa = e1[e1.fault_type == "overall"].groupby("method").false_alarm_rate.mean()
    out.append(
        f"False-alarm rate on clean samples: hybrid {fa.get('hybrid', np.nan):.4f}, "
        f"edge Holt-Winters {fa.get('edge_hw', np.nan):.4f}, "
        f"central {fa.get('central', np.nan):.4f}."
    )
    e2 = d["e2_reconstruction"]
    cross = e2.groupby("seed").crossover_min.first()
    # Mean over seeds of the per-seed mean, as in the E2 table.
    p = (
        e2[e2.kind == "pressure"]
        .groupby(["seed", "gap_min", "method"])
        .mae.mean()
        .groupby(["gap_min", "method"])
        .mean()
        .unstack()
    )
    longest = p.index.max()
    out.append(
        f"Reconstruction: the calibration week puts the temporal/spatial crossover at "
        f"{pm(cross, 0)} min. For {longest}-min pressure gaps the MAE is "
        f"{p.loc[longest, 'holt_winters']:.3f} m (Holt-Winters), {p.loc[longest, 'spatial']:.3f} m "
        f"(spatial) and {p.loc[longest, 'linear_offline']:.3f} m (linear interpolation, which "
        f"needs the future)."
    )
    pol = d["e3_policies"].groupby("policy").binary_bytes_per_station_day.mean()
    js = d["e3_policies"].groupby("policy").json_bytes_per_station_day.mean()
    out.append(
        f"Uplink: delta sends {pol['delta'] / pol['validated']:.2f} of the bytes of the "
        f"validated policy; SensorThings JSON is {js['validated'] / pol['validated']:.0f} times "
        f"the binary frame size for the same records."
    )
    e5 = d["e5_training"].groupby(["paradigm", "cold_start"]).one_step_rmse_m.mean().unstack()
    cs = e5[True]
    out.append(
        f"Cold-start station, one-step RMSE: local {cs['local']:.3f} m, centralised "
        f"{cs['centralised']:.3f} m, federated {cs['federated']:.3f} m, federated with "
        f"fine-tuning {cs['federated_finetuned']:.3f} m."
    )
    e6 = d["e6_twin"].groupby("input").rmse_unmonitored_m.mean()
    out.append(
        f"Twin state error at unmonitored nodes: raw {e6['raw']:.2f} m, edge-validated "
        f"{e6['edge_validated']:.2f} m, hybrid {e6['hybrid_validated']:.2f} m, clean "
        f"{e6['clean']:.2f} m."
    )
    e7 = (
        d["e7_events"]
        .groupby("architecture")[["event_samples_reconstructed", "faults_raised_as_events"]]
        .mean()
    )
    out.append(
        "Process events: share of event samples reconstructed away "
        + ", ".join(f"{a} {v:.3f}" for a, v in e7.event_samples_reconstructed.items())
        + "; share of sensor faults raised as events "
        + ", ".join(f"{a} {v:.2f}" for a, v in e7.faults_raised_as_events.items())
        + "."
    )
    return out


def build(cfg: Config, results: Path) -> tuple[str, str]:
    raw = results / "raw"
    d = {p.stem: pd.read_csv(p) for p in sorted(raw.glob("*.csv"))}
    figs = results / "figures"
    fig_e1(d["e1_detection"], figs)
    fig_e2(d["e2_reconstruction"], figs)
    fig_e3(d["e3_policies"], d["e3_epsilon"], figs)
    fig_e6(d["e6_twin"], figs)
    seeds = sorted(d["e1_detection"].seed.unique())
    e1 = d["e1_detection"]
    order = list(METHOD_NAMES)
    t_e1 = table(
        e1[e1.fault_type == "overall"],
        ["method"],
        {
            "precision": "precision",
            "recall": "recall",
            "f1": "F1",
            "event_recall": "event recall",
            "event_precision": "event precision",
            "delay_min": "delay (min)",
            "false_alarm_rate": "false-alarm rate",
            "process_event_alarm_rate": "alarms on process events",
        },
        order=order,
        rename=lambda m: METHOD_NAMES.get(m, m),
    )
    t_e1t = table(
        e1[
            e1.fault_type.isin(
                ["spike", "stuck", "noise_burst", "bias", "drift", "gap_short", "gap_long"]
            )
        ],
        ["method", "fault_type"],
        {"recall": "recall", "f1": "F1", "delay_min": "delay (min)"},
        rename=lambda m: METHOD_NAMES.get(m, m),
        digits=2,
    )
    e2 = d["e2_reconstruction"]
    t_e2 = {}
    for kind, unit in (("pressure", "m"), ("flow", "L/s"), ("level", "m")):
        sub = e2[e2.kind == kind]
        piv = sub.groupby(["seed", "gap_min", "method"]).mae.mean().reset_index()
        methods = [
            "last_value",
            "linear_offline",
            "seasonal_naive",
            "holt_winters",
            "mlp",
            "spatial",
            "hybrid",
        ]
        lines = ["| gap (min) | " + " | ".join(methods) + " |", "|---|" + "---|" * len(methods)]
        for gm, g in piv.groupby("gap_min"):
            lines.append(
                f"| {gm} | " + " | ".join(pm(g[g.method == m].mae, 3) for m in methods) + " |"
            )
        t_e2[f"{kind} ({unit})"] = "\n".join(lines)
    t_e3 = table(
        d["e3_policies"],
        ["policy"],
        {
            "binary_bytes_per_station_day": "binary B/station/day",
            "json_bytes_per_station_day": "JSON B/station/day",
            "frames_per_station_day": "frames/station/day",
            "mean_frame_fill": "frame fill (of 51 B)",
            "fault_latency_min": "latency (min)",
        },
        digits=1,
    )
    t_e3e = table(
        d["e3_epsilon"],
        ["eps_factor"],
        {
            "binary_bytes_per_station_day": "binary B/station/day",
            "cloud_error_vs_edge": "error vs edge (fraction of range)",
            "cloud_error_vs_truth": "error vs truth (fraction of range)",
        },
        digits=4,
    )
    t_e4 = table(
        d["e4_outage"],
        ["outage_h", "architecture"],
        {
            "fault_events_in_window": "fault events in outage",
            "events_flagged_during_outage": "flagged at the station during outage",
            "mean_backlog_frames": "backlog (frames)",
            "backfill_h": "backfill (h)",
            "cloud_up_to_date_after_h": "cloud up to date after (h)",
        },
        digits=2,
    )
    e5 = d["e5_training"]
    e5g = (
        e5.groupby(["seed", "paradigm", "cold_start"])
        .agg(
            one=("one_step_rmse_m", "mean"),
            day=("day_ahead_rmse_m", "mean"),
            up=("bytes_up", "first"),
            down=("bytes_down", "first"),
        )
        .reset_index()
    )
    warm = e5g[~e5g.cold_start].rename(columns={"one": "one_warm", "day": "day_warm"})
    cold = e5g[e5g.cold_start][["seed", "paradigm", "one", "day"]].rename(
        columns={"one": "one_cold", "day": "day_cold"}
    )
    t_e5 = table(
        warm.merge(cold, on=["seed", "paradigm"]),
        ["paradigm"],
        {
            "one_warm": "one-step RMSE (m)",
            "day_warm": "day-ahead RMSE (m)",
            "one_cold": "cold start one-step (m)",
            "day_cold": "cold start day-ahead (m)",
            "up": "bytes up",
            "down": "bytes down",
        },
        order=["local", "centralised", "federated", "federated_finetuned"],
    )
    t_e6 = table(
        d["e6_twin"],
        ["input"],
        {
            "rmse_monitored_m": "RMSE monitored (m)",
            "rmse_unmonitored_m": "RMSE unmonitored (m)",
            "p95_abs_error_m": "95th pct |error| (m)",
            "degraded_steps": "degraded steps",
            "resyncs": "resyncs",
        },
        order=["raw", "edge_validated", "hybrid_validated", "clean"],
        digits=2,
    )
    t_e7 = table(
        d["e7_events"],
        ["architecture"],
        {
            "process_events_raised": "process events raised",
            "event_samples_reconstructed": "event samples reconstructed",
            "events_reconstructed_away": "events reconstructed away",
            "faults_raised_as_events": "faults raised as events",
        },
        order=["edge_only", "central_only", "hybrid"],
    )
    t_x1 = _single_row(
        d["x1_maintenance"],
        {
            "false_alarms_without_log": "spatial false alarms, no log",
            "false_alarms_with_log": "with log",
            "fault_alarms_suppressed": "fault alarms suppressed",
        },
    )
    t_x2 = _single_row(
        d["x2_temperature"],
        {
            "mae_without_temperature_l_s": "demand MAE without temperature (L/s)",
            "mae_with_temperature_l_s": "with temperature (L/s)",
            "mean_demand_l_s": "mean demand (L/s)",
        },
    )
    t_fp = footprint_table(results / "edge_footprint.csv")
    head = (
        f"Configuration `{cfg.name}`, seeds {', '.join(map(str, seeds))}; mean ± sample standard "
        "deviation over seeds; test week only unless stated."
    )
    key = "\n".join(f"- {s}" for s in findings(d))
    summary = (
        "\n\n".join(
            [
                "# Results summary",
                head,
                "## Key numbers",
                key,
                "## E1 detection (overall, non-gap faults)",
                t_e1,
                "### E1 by fault type",
                t_e1t,
                "## E2 reconstruction MAE by gap length",
                *[f"### {k}\n\n{v}" for k, v in t_e2.items()],
                "## E3 uplink policies",
                t_e3,
                "### E3 delta policy versus epsilon",
                t_e3e,
                "## E4 outage",
                t_e4,
                "## E5 training paradigms (pressure loggers)",
                t_e5,
                "## E6 twin state estimation",
                t_e6,
                "## E7 process events versus sensor faults",
                t_e7,
                "## Maintenance log (spatial alarms, test week)",
                t_x1,
                "## External data (day-ahead total demand)",
                t_x2,
                *(["## Edge footprint", t_fp] if t_fp else []),
            ]
        )
        + "\n"
    )
    readme = "\n\n".join(
        [
            head,
            key,
            "**E1 detection** (overall, non-gap faults)",
            t_e1,
            "**E2 reconstruction**, pressure MAE by gap length",
            t_e2["pressure (m)"],
            "**E3 uplink**",
            t_e3,
            "**E6 twin state estimation**",
            t_e6,
            "**E7 process events**",
            t_e7,
            *(["**Edge footprint**", t_fp] if t_fp else []),
            "![Recall by fault type](results/figures/e1_recall_by_fault.png)",
            "![Reconstruction error versus gap length]"
            "(results/figures/e2_reconstruction_vs_gap.png)",
            "![Uplink bytes and delta trade-off](results/figures/e3_uplink.png)",
            "All tables, including E4, E5 and the per-fault-type breakdown, are in "
            "[results/summary.md](results/summary.md).",
        ]
    )
    return summary, readme


def footprint_table(path: Path) -> str:
    """Table from ``edge_footprint.csv`` (written by ``flowmine experiments footprint``)."""
    if not path.exists():
        return ""
    fp = pd.read_csv(path)
    lines = [
        "| forecaster | parameters | model bytes | buffer (samples) | µs/sample CPython "
        "| µs/sample MicroPython |",
        "|---|---|---|---|---|---|",
    ]
    for r in fp.itertuples():
        lines.append(
            f"| {r.forecaster} | {r.parameters} | {r.model_bytes} | {r.buffer_samples} | "
            f"{r.us_per_sample_cpython} | {r.us_per_sample_micropython} |"
        )
    note = (
        "Measured on a laptop (CPython 3.12 and the MicroPython Unix port) for one "
        "pressure sensor; these are not ESP32 timings."
    )
    return note + "\n\n" + "\n".join(lines)


def _single_row(df: pd.DataFrame, cols: dict[str, str]) -> str:
    head = "| " + " | ".join(cols.values()) + " |"
    sep = "|" + "---|" * len(cols)
    return "\n".join([head, sep, "| " + " | ".join(pm(df[c], 1) for c in cols) + " |"])


def write(cfg: Config, results: Path, readme: Path | None) -> None:
    summary, block = build(cfg, results)
    (results / "summary.md").write_text(summary)
    if readme is None:
        return
    text = readme.read_text()
    if BEGIN not in text or END not in text:
        raise ValueError(f"{readme} has no results markers")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    readme.write_text(pre + BEGIN + "\n\n" + block + "\n\n" + END + post)
